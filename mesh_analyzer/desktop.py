"""Native desktop shell for the local Meshtastic dashboard.

Windows uses WebView2 and never falls back to a browser. macOS uses the
system WebKit (Cocoa). On Linux, app.run() opens the default browser when no
native WebView backend (GTK/Qt) is available.
"""
from __future__ import annotations

import os
from pathlib import Path
import sys


def native_window_icon() -> Path | None:
    """Find the actual Windows ICO used by pywebview WinForms.

    The PE icon alone does not necessarily become the native WebView2 window icon.
    PyInstaller --onefile extracts --add-data files under sys._MEIPASS.
    """
    base = Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parents[1]))
    # Inno Setup copies this icon to an installed, stable path shared by
    # Desktop/Start shortcuts. Point the WebView2 host there too when present:
    # a PyInstaller onefile _MEIPASS path changes on every launch.
    if getattr(sys, "frozen", False):
        stable = Path(sys.executable).resolve().parent / "branding" / "mesh-analyzer.ico"
        if stable.is_file():
            return stable
    icon = base / "branding" / "mesh-analyzer.ico"
    if icon.is_file():
        return icon
    if getattr(sys, "frozen", False):
        raise RuntimeError(
            "Ícone nativo PT2VHF ausente do pacote Windows. "
            "Reinstale uma versão que inclua branding/mesh-analyzer.ico."
        )
    # Source checkout: branding/build_icons.py may not have been run yet.
    return None


class PDFExportBridge:
    """Native save dialog for PDFs generated by the authenticated local backend.

    The JavaScript caller holds the PDF bytes transiently; only a validated PDF
    may reach disk through an explicit user-chosen native save destination.
    """

    def __init__(self, profile=None):
        # This must NOT be public: pywebview traverses public js_api fields
        # recursively, which exposes WinForms/WebView2 native COM objects and
        # can crash the new instance during the automatic updater restart.
        self._window = None
        self._profile = profile

    def save_backup(self, file_name: str) -> dict:
        """#166: copia um backup já gerado em backups/ para o local escolhido."""
        import shutil
        from .backup import backup_file
        source = backup_file(Path(self._profile), file_name)
        if self._window is None:
            raise RuntimeError("Janela nativa não disponível")
        import webview
        result = self._window.create_file_dialog(
            webview.SAVE_DIALOG, save_filename=source.name,
            file_types=("Backup do Mesh Analyzer (*.zip)",))
        if not result:
            return {"saved": False, "cancelled": True}
        dest = Path(result[0] if isinstance(result, (tuple, list)) else result)
        if dest.suffix.lower() != ".zip":
            dest = dest.with_suffix(".zip")
        shutil.copyfile(source, dest)
        return {"saved": True, "filename": dest.name, "size": dest.stat().st_size}

    def save_pdf(self, data_base64: str, suggested_name: str = "") -> dict:
        import base64
        if not isinstance(data_base64, str) or len(data_base64) > 24_000_000:
            raise ValueError("PDF excede o limite de exportação")
        try:
            data = base64.b64decode(data_base64, validate=True)
        except (ValueError, base64.binascii.Error) as exc:
            raise ValueError("Conteúdo PDF inválido") from exc
        if not 100 <= len(data) <= 16_000_000 or not data.startswith(b"%PDF-") or b"%%EOF" not in data[-2048:]:
            raise ValueError("O arquivo recebido não é um PDF completo")
        filename = Path(str(suggested_name)).name
        if not filename.lower().endswith(".pdf") or len(filename) > 150:
            filename = "PT2VHF-Mesh-Analyzer-Relatorio.pdf"
        if self._window is None:
            raise RuntimeError("Janela nativa não disponível")
        import webview
        result = self._window.create_file_dialog(
            webview.SAVE_DIALOG,
            save_filename=filename,
            file_types=("Arquivos PDF (*.pdf)",),
        )
        if not result:
            return {"saved": False, "cancelled": True}
        path = Path(result[0] if isinstance(result, (tuple, list)) else result)
        if path.suffix.lower() != ".pdf":
            path = path.with_suffix(".pdf")
        path.write_bytes(data)
        return {"saved": True, "filename": path.name, "size": len(data)}


def open_desktop_window(url: str, profile: Path) -> None:
    try:
        import webview
    except ImportError as exc:
        raise RuntimeError("Componente desktop WebView indisponível. Reinstale o aplicativo.") from exc

    # Keep the running WebView2 window grouped with the installed Start-menu
    # and desktop shortcuts, not with Python/Edge.
    if os.name == "nt":
        try:
            import ctypes
            ctypes.windll.shell32.SetCurrentProcessExplicitAppUserModelID(
                "PT2VHF.MeshAnalyzer")
        except (AttributeError, OSError):
            pass  # The branded EXE resource still supplies the taskbar icon.

    pdf_bridge = PDFExportBridge(profile)
    window = webview.create_window(
        "PT2VHF Mesh Analyzer",
        url=url,
        js_api=pdf_bridge,
        width=1450,
        height=900,
        min_size=(950, 600),
        resizable=True,
        confirm_close=False,
    )
    if window is None:
        raise RuntimeError("Não foi possível criar a janela desktop.")
    pdf_bridge._window = window
    # Runs on the main thread; returns only after the last desktop window closes.
    # Windows 10 1809+ requires Microsoft Edge WebView2 Runtime (Evergreen), if absent.
    windows = os.name == "nt"
    try:
        icon_path = native_window_icon() if windows else None
        # macOS: Cocoa/WebKit; Linux: GTK or Qt, whichever pywebview finds.
        webview.start(gui="edgechromium" if windows else None, debug=False,
                      private_mode=False, storage_path=str(profile),
                      icon=str(icon_path) if icon_path else None)
    except Exception as exc:
        raise RuntimeError(
            "Falha ao iniciar WebView2. Verifique o Microsoft Edge WebView2 Runtime."
            if windows else "Falha ao iniciar a janela nativa (WebView)."
        ) from exc
